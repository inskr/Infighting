'use strict';

const assert = require('node:assert/strict');
const test = require('node:test');
const vm = require('node:vm');
const zlib = require('node:zlib');
const { FakeDocument } = require('./helpers/fake-dom.cjs');

let PreviewBundle;
try {
  PreviewBundle = require('../scripts/search-preview-bundle.js');
} catch (error) {
  PreviewBundle = { loadError: error };
}

function api() {
  assert.equal(PreviewBundle.loadError, undefined, 'search preview bundle generator should load');
  return PreviewBundle;
}

function posts() {
  return [
    {
      id: 'metadata-match',
      title: 'STM32 metadata result',
      summary: 'Fast summary',
      tags: ['STM32'],
      date: '2026-08-24',
      type: 'post',
      content: 'Full article body is excluded.',
    },
    {
      id: 'body-only',
      title: 'Unrelated title',
      summary: '',
      tags: [],
      date: '2026-08-23',
      type: 'post',
      content: 'STM32 appears only in the authoritative full-text body.',
    },
    {
      id: 'metadata-second',
      title: 'STM32 secondary result',
      summary: '',
      tags: [],
      date: '2026-08-22',
      type: 'post',
      content: '',
    },
  ];
}

function execute(source, search) {
  const document = new FakeDocument();
  const results = document.createElement('div');
  results.setAttribute('id', 'search-results');
  document.body.appendChild(results);
  const calls = { announcements: 0, fetches: 0 };
  const root = {
    document,
    location: { search },
    fetch() { calls.fetches += 1; },
    SiteShell: { announce() { calls.announcements += 1; } },
  };

  vm.runInNewContext(source, {
    decodeURIComponent,
    document,
    encodeURIComponent,
    location: root.location,
    window: root,
  });
  return { calls, document, results, root };
}

test('preview bundle output is deterministic, metadata-only, self-contained, and lightweight', () => {
  // Break caught: generated bytes drift, embed article bodies, or reintroduce the parser dependency chain.
  const first = api().renderSearchPreviewBundle(posts());
  const second = api().renderSearchPreviewBundle(posts().map((post) => ({ ...post })));

  assert.equal(first, second);
  assert.match(first, /^\/\/ Auto-generated Search metadata preview\./);
  assert.match(first, /metadata-match/);
  assert.doesNotMatch(first, /Full article body|authoritative full-text body|"content"/);
  assert.doesNotMatch(first, /SearchCore|ContentCards|window\.POSTS|fetch\s*\(/);
  assert.ok(Buffer.byteLength(first) <= 16 * 1024);
  assert.ok(zlib.gzipSync(first).length <= 8 * 1024);
});

test('valid initial q renders every metadata match at parser time with a comparable fingerprint', () => {
  // Break caught: the parser preview renders only top-1 or cannot prove equivalence with authoritative visible cards.
  const view = execute(api().renderSearchPreviewBundle(posts()), '?q=%20STM32%20');
  const state = view.root.SearchPreviewState;

  assert.equal(state.kind, 'generated-metadata-preview');
  assert.equal(state.query, 'STM32');
  assert.equal(state.preview, true);
  assert.equal(state.results, view.results);
  assert.deepEqual(Array.from(state.resultIds), ['metadata-match', 'metadata-second']);
  assert.equal(
    state.fingerprint,
    '[["metadata-match","STM32 metadata result","2026-08-24",["STM32"],"Fast summary"],["metadata-second","STM32 secondary result","2026-08-22",[],""]]'
  );
  assert.equal(view.results.querySelectorAll('.post-card').length, 2);
  assert.deepEqual(
    view.results.querySelectorAll('h3').map((heading) => heading.textContent),
    ['STM32 metadata result', 'STM32 secondary result']
  );
  assert.equal(view.results.querySelector('h2'), null);
  assert.equal(view.results.getAttribute('data-search-preview'), 'true');
  assert.equal(view.results.getAttribute('data-search-active'), 'true');
  assert.equal(view.results.getAttribute('data-search-query'), 'STM32');
  assert.equal(view.results.getAttribute('aria-busy'), 'true');
  assert.deepEqual(view.calls, { announcements: 0, fetches: 0 });
});

test('empty and malformed initial q skip preview work without throwing or starting full search', () => {
  // Break caught: the parser bundle turns absent/invalid URL state into search or partial DOM state.
  const source = api().renderSearchPreviewBundle(posts());
  for (const [search, reason] of [
    ['', 'empty-query'],
    ['?q=', 'empty-query'],
    ['?q=%20%20', 'empty-query'],
    ['?q=%E0%A4%A', 'malformed-query'],
  ]) {
    const view = execute(source, search);
    assert.equal(view.root.SearchPreviewState.preview, false, search);
    assert.equal(view.root.SearchPreviewState.reason, reason, search);
    assert.equal(view.results.children.length, 0, search);
    assert.equal(view.results.getAttribute('aria-busy'), null, search);
    assert.deepEqual(view.calls, { announcements: 0, fetches: 0 }, search);
  }
});

test('generated renderer treats hostile metadata as text and keeps static article/tag URL contracts', () => {
  // Break caught: build-time metadata becomes executable parser-time HTML or unsafe navigation.
  const source = api().renderSearchPreviewBundle([{
    id: 'alpha/beta',
    title: '<img src=x onerror=alert(1)> needle',
    summary: '<svg> needle </svg>',
    tags: ['<script>alert(1)</script>'],
    date: '2026-08-24',
    content: '',
  }]);
  const view = execute(source, '?q=needle');
  const card = view.results.querySelector('.post-card');

  assert.equal(card.querySelector('h3').textContent, '<img src=x onerror=alert(1)> needle');
  assert.equal(card.querySelector('h3').querySelector('a').getAttribute('href'), 'posts/alpha%2Fbeta.html');
  assert.equal(card.querySelector('.tag').getAttribute('href'), 'tags.html?tag=%3Cscript%3Ealert(1)%3C%2Fscript%3E');
  assert.equal(card.querySelector('.post-summary').textContent, '<svg> needle </svg>');
  assert.equal(card.querySelectorAll('img').length, 0);
  assert.equal(card.querySelectorAll('script').length, 0);
  assert.equal(card.querySelectorAll('svg').length, 0);
});
